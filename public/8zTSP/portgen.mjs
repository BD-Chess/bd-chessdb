// Port of Lyle McGeoch's portgen.c (24 June 1999), DIMACS TSP Challenge.
// https://archive.dimacs.rutgers.edu/Challenges/TSP/codes.tar
// Integer arithmetic stays exact in JS (all states < 1e9); divide truncates as C.
export function* dimacsChunks(n,seed=n) {
  if(![100000,1000000,10000000].includes(n) || seed!==n)throw Error('Unsupported standard DIMACS instance');
  const enc=new TextEncoder(),arr=new Int32Array(55);let a=0,b=24,last=seed,next=1;
  arr[0]=last;
  for(let i=1;i<55;i++){const ii=21*i%55;arr[ii]=next;next=last-next;if(next<0)next+=1000000000;last=arr[ii];}
  function rand(){if(a--===0)a=54;if(b--===0)b=54;let t=arr[a]-arr[b];if(t<0)t+=1000000000;arr[a]=t;return t;}
  for(let i=0;i<165;i++)rand();
  const name=n===100000?'E100k.0':n===1000000?'E1M.0':'E10M.0';
  yield enc.encode(`NAME : ${name}\nCOMMENT : DIMACS Challenge instance, generated by portgen/portcgen\nCOMMENT : command line: portgen ${n} ${seed} > ${name}\nCOMMENT : generator source: https://archive.dimacs.rutgers.edu/Challenges/TSP/codes.tar\nTYPE : TSP\nDIMENSION : ${n}\nEDGE_WEIGHT_TYPE : EUC_2D\nNODE_COORD_SECTION\n`);
  let batch=[];
  for(let id=1;id<=n;id++){
    batch.push(`${id} ${Math.trunc(rand()/1000)} ${Math.trunc(rand()/1000)}\n`);
    if(batch.length===8192){yield enc.encode(batch.join(''));batch=[];}
  }
  if(batch.length)yield enc.encode(batch.join(''));
  yield enc.encode('EOF\n');
}
