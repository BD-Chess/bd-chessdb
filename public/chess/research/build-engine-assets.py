#!/usr/bin/env python3
"""Generate only the LAB optional-engine allowlist. Preserve original runtimes.

Source offers/licenses are linked, not mandatory offline runtime downloads.
Hashes are verified against existing pinned donor manifests before publication.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHA = lambda b: hashlib.sha256(b).hexdigest()
packages = []

def package(mode, variant, version, files, *, combined=None, network=None, embedded_network=None, source='', license=''):
    records=[]
    for name in files:
        data=(ROOT/name).read_bytes()
        records.append(dict(path=name, bytes=len(data), sha256=SHA(data)))
    row=dict(mode=mode, variant=variant, version=version, files=records, source=source, license=license)
    if combined:
        row['combined']=combined
        h=hashlib.sha256()
        for name in combined['parts']:
            h.update((ROOT/name).read_bytes())
        assert h.hexdigest()==combined['sha256'], 'Combined donor SHA mismatch'
    if network:
        row['network']=network
    if embedded_network:
        row['embeddedNetwork']=embedded_network
    row['bytes']=sum(f['bytes'] for f in records)+(network['bytes'] if network else 0)
    row['identity']=SHA(json.dumps(row,sort_keys=True,separators=(',',':')).encode())
    packages.append(row)

sf='vendor/stockfish-full/v19.0.1/'
parts=json.loads((ROOT/sf/'wasm-parts.json').read_text())
for variant,name in [('single','stockfish-19-single'),('threaded','stockfish-19')]:
    donor=parts[name+'.wasm']
    for item in donor['parts']:
        data=(ROOT/sf/item['path']).read_bytes()
        assert len(data)==item['bytes'] and SHA(data)==item['sha256']
    package('sf-full',variant,'19.0.1',[sf+name+'.js',sf+'wasm-chunks.js']+[sf+p['path'] for p in donor['parts']],
            combined=dict(bytes=donor['bytes'],sha256=donor['sha256'],parts=[sf+p['path'] for p in donor['parts']]),
            embedded_network=dict(name='nn-1a298aa575a0.nnue',sha256='1a298aa575a085434d29027978dc36867fe9c5bcea9376654b7a8eba1e52dfc2',storage='embedded in original WASM'),
            source='engines/PUBLIC_FREE_OPERATIONS.md',license='GPL-3.0')

ber='vendor/berserk/v14-5b8d6c93/'
network=dict(storage='IndexedDB',database='ChessBest:LAB:engine-networks:v1',store='networks',
             sha256='9b84c340af7e45f6e07f0046235ccb327f4ae0840c8ee2c4b97b99121e5c5084',bytes=25201924)
assert SHA((ROOT/ber/'berserk-emscripten.wasm').read_bytes())=='0cffe539d41787c8cc2963911e24fe0bdf5319bae1fe03fae243642e8cda9372'
package('berserk','scalar','14',[ber+'berserk-host.js',ber+'berserk-emscripten.js',ber+'berserk-emscripten.wasm'],
        network=network,source='engines/PUBLIC_FREE_OPERATIONS.md',license='GPL-3.0')

rle='engines/reckless/v0.10.0-a6fa482c-r8/'
donor=json.loads((ROOT/rle/'manifest.json').read_text())
rle_files=['adapter.mjs','reckless-engine.js','reckless-worker.js','reckless.js']+donor['combined_wasm']['parts']
for name in rle_files:
    data=(ROOT/rle/name).read_bytes(); pin=donor['files'][name]
    assert len(data)==pin['bytes'] and SHA(data)==pin['sha256']
package('reckless','single-thread-simd128',donor['version'],['engines/reckless/adapter.mjs']+[rle+p for p in rle_files],
        combined={**donor['combined_wasm'],'parts':[rle+p for p in donor['combined_wasm']['parts']]},embedded_network={**donor['nnue'],'storage':'embedded in original WASM'},source=rle+'SOURCE.md',license='AGPL-3.0-only')

lc='engines/lc0/v0.32.1-maia1900-r8/'
donor=json.loads((ROOT/lc/'manifest.json').read_text())
lc_pins={f['path']:f for f in donor['files']}
lc_files=['adapter.mjs','worker.mjs','chess.mjs','encoder.mjs','neural.mjs','policy-map.mjs','search.mjs',
          'runtime/ort.wasm.min.mjs','runtime/ort-wasm-simd-threaded.mjs','runtime/ort-wasm-simd-threaded.wasm','maia-1900.onnx']
for name in lc_files:
    data=(ROOT/lc/name).read_bytes(); pin=lc_pins[name]
    assert len(data)==pin['bytes'] and SHA(data)==pin['sha256']
package('lc0','wasm-simd-1thread-browser-puct','0.32.1-maia1900-r8',['engines/lc0/adapter.mjs']+[lc+p for p in lc_files],
        source=lc+'README.md',license='GPL-3.0-or-later / ORT MIT')

out=ROOT/'js/8zc-engine-assets-manifest.js'
text='/* Generated by research/build-engine-assets.py. Public immutable LAB runtime only. */\n'+\
     '(function(root){const manifest='+json.dumps(dict(schema='chessbest.LAB.engine-assets.v1',prefix='chessbest-LAB-engine-assets-v1-',packages=packages),indent=2)+\
     ';if(typeof module==="object"&&module.exports)module.exports=manifest;else root.ChessEngineAssetManifest=manifest;})(typeof self==="object"?self:globalThis);\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
    assert out.read_text()==text, 'Stale LAB optional engine manifest'
else:
    out.write_text(text)
print(json.dumps([dict(mode=p['mode'],variant=p['variant'],bytes=p['bytes'],identity=p['identity'],files=len(p['files'])) for p in packages],indent=2))
